-- =====================================================================
-- 01_setup.sql : warehouse, database, schemas, roles, S3 integration
-- Layered architecture:  RAW (as-landed) -> ODS (current state) -> ANALYTICS (dbt star schema)
-- =====================================================================
USE ROLE SYSADMIN;

CREATE WAREHOUSE IF NOT EXISTS RETAIL_WH
  WAREHOUSE_SIZE = 'XSMALL'
  AUTO_SUSPEND = 60            -- cost control: suspend after 1 idle minute
  AUTO_RESUME = TRUE
  INITIALLY_SUSPENDED = TRUE;

CREATE DATABASE IF NOT EXISTS RETAIL_DB;
CREATE SCHEMA IF NOT EXISTS RETAIL_DB.RAW;        -- immutable landing copy, with lineage columns
CREATE SCHEMA IF NOT EXISTS RETAIL_DB.ODS;        -- operational data store: deduped, latest state
CREATE SCHEMA IF NOT EXISTS RETAIL_DB.STAGING;    -- dbt staging views
CREATE SCHEMA IF NOT EXISTS RETAIL_DB.SNAPSHOTS;  -- dbt SCD2 snapshots
CREATE SCHEMA IF NOT EXISTS RETAIL_DB.MARTS;      -- dbt dimensional model (BI-facing)
CREATE SCHEMA IF NOT EXISTS RETAIL_DB.AUDIT;      -- load logging

-- ---------- RBAC ----------
USE ROLE SECURITYADMIN;
CREATE ROLE IF NOT EXISTS LOADER;        -- Python / SnapLogic: write RAW, call ODS proc
CREATE ROLE IF NOT EXISTS TRANSFORMER;   -- dbt: read ODS, build STAGING/SNAPSHOTS/MARTS
CREATE ROLE IF NOT EXISTS REPORTER;      -- Tableau / Power BI: read MARTS only
GRANT ROLE LOADER, TRANSFORMER, REPORTER TO ROLE SYSADMIN;

GRANT USAGE ON WAREHOUSE RETAIL_WH TO ROLE LOADER;
GRANT USAGE ON WAREHOUSE RETAIL_WH TO ROLE TRANSFORMER;
GRANT USAGE ON WAREHOUSE RETAIL_WH TO ROLE REPORTER;
GRANT USAGE ON DATABASE RETAIL_DB TO ROLE LOADER;
GRANT USAGE ON DATABASE RETAIL_DB TO ROLE TRANSFORMER;
GRANT USAGE ON DATABASE RETAIL_DB TO ROLE REPORTER;

GRANT ALL ON SCHEMA RETAIL_DB.RAW   TO ROLE LOADER;
GRANT ALL ON SCHEMA RETAIL_DB.ODS   TO ROLE LOADER;
GRANT ALL ON SCHEMA RETAIL_DB.AUDIT TO ROLE LOADER;
GRANT USAGE ON SCHEMA RETAIL_DB.ODS TO ROLE TRANSFORMER;
GRANT SELECT ON FUTURE TABLES IN SCHEMA RETAIL_DB.ODS TO ROLE TRANSFORMER;
GRANT USAGE ON FUTURE FUNCTIONS IN SCHEMA RETAIL_DB.ODS TO ROLE TRANSFORMER;
GRANT CREATE SCHEMA ON DATABASE RETAIL_DB TO ROLE TRANSFORMER;  -- per-developer dev schemas
GRANT ALL ON SCHEMA RETAIL_DB.STAGING   TO ROLE TRANSFORMER;
GRANT ALL ON SCHEMA RETAIL_DB.SNAPSHOTS TO ROLE TRANSFORMER;
GRANT ALL ON SCHEMA RETAIL_DB.MARTS     TO ROLE TRANSFORMER;
GRANT USAGE ON SCHEMA RETAIL_DB.MARTS TO ROLE REPORTER;
GRANT SELECT ON FUTURE TABLES IN SCHEMA RETAIL_DB.MARTS TO ROLE REPORTER;
GRANT SELECT ON FUTURE VIEWS  IN SCHEMA RETAIL_DB.MARTS TO ROLE REPORTER;

-- ---------- S3 storage integration (no keys stored in Snowflake) ----------
USE ROLE ACCOUNTADMIN;
CREATE STORAGE INTEGRATION IF NOT EXISTS S3_RETAIL_INT
  TYPE = EXTERNAL_STAGE
  STORAGE_PROVIDER = 'S3'
  ENABLED = TRUE
  STORAGE_AWS_ROLE_ARN = '<SnowflakeRoleArn output from aws/template.yaml>'
  STORAGE_ALLOWED_LOCATIONS = ('s3://<RawBucketName>/raw/');
GRANT USAGE ON INTEGRATION S3_RETAIL_INT TO ROLE SYSADMIN;
-- DESC INTEGRATION S3_RETAIL_INT;  -> copy STORAGE_AWS_IAM_USER_ARN + EXTERNAL_ID back into the CFN params

USE ROLE SYSADMIN;
USE SCHEMA RETAIL_DB.RAW;

CREATE FILE FORMAT IF NOT EXISTS RAW.CSV_FMT
  TYPE = CSV
  SKIP_HEADER = 1
  FIELD_OPTIONALLY_ENCLOSED_BY = '"'
  NULL_IF = ('', 'NULL')
  EMPTY_FIELD_AS_NULL = TRUE
  ERROR_ON_COLUMN_COUNT_MISMATCH = TRUE;

CREATE STAGE IF NOT EXISTS RAW.S3_RAW_STAGE
  STORAGE_INTEGRATION = S3_RETAIL_INT
  URL = 's3://<RawBucketName>/raw/'
  FILE_FORMAT = RAW.CSV_FMT;

GRANT USAGE ON STAGE RAW.S3_RAW_STAGE TO ROLE LOADER;
GRANT USAGE ON FILE FORMAT RAW.CSV_FMT TO ROLE LOADER;
